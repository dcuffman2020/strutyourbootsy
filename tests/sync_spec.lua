local ns={}
assert(loadfile("Sync.lua"))("StrutYourBootsy",ns)
local S=assert(ns.Sync)
local host=S.New(100)
assert(S.ShouldAdvertise(host,100))
S.Advertised(host,100)
assert(not S.ShouldAdvertise(host,119))
assert(S.ShouldAdvertise(host,120))
assert(S.Tick(host,200,true)=="active")
assert(S.Tick(host,201,false)=="paused")
assert(S.Tick(host,499,false)=="paused")
assert(S.Tick(host,500,false)=="ended")
assert(not S.ShouldAdvertise(host,521))
local peer=S.New(0)
assert(S.Request(peer,"contestant",1))
assert(not S.Request(peer,"spectator",2))
assert(S.ShouldRetry(peer,1))
S.SentRequest(peer,1)
assert(not S.ShouldRetry(peer,8))
assert(S.ShouldRetry(peer,9))
assert(S.Confirmed(peer,"contestant"))
assert(not S.ShouldRetry(peer,20))
local recovering=S.New(0)
assert(S.Tick(recovering,1,false)=="paused")
assert(S.Tick(recovering,299,false)=="paused")
assert(S.Tick(recovering,300,false)=="ended")
print("Sync spec passed")
