local ns={}
assert(loadfile("Protocol.lua"))("StrutYourBootsy",ns)
local P=assert(ns.Protocol)
local w=assert(P.Encode("HELLO","-",1,"v1"))
assert(w=="SYB1|HELLO|-|1|v1")
local p=assert(P.Decode(w))
assert(p.kind=="HELLO" and p.seq==1 and p.session=="-")
local function bad(w)
 assert(P.Decode(w)==nil)
end
bad("SYB1|HELLO|-|01|v1")
bad("SYB1|HELLO|-|0|v1")
bad("SYB1|HELLO|-|1|v1|extra")
bad("SYB1|UNKNOWN|-|1|v1")
bad("SYB1|HELLO|-|1|bad payload")
bad(string.rep("x",256))
assert(P.Encode("BALLOT","session-42",1,"player1.5_player2.3"))
assert(P.Encode("BALLOT","session-42",1,"bad|payload")==nil)
print("Protocol spec passed")
